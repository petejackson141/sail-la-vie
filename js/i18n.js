/* ============================================================
   i18n — translation lookup, DOM application, and language switching.
   TRANSLATIONS holds one flat key->string dict per language. currentLang
   drives both t() and date/time locale formatting (see currentLocale()).
   Add a new language by adding another entry to TRANSLATIONS and a chip
   in Settings — everything else picks it up automatically.
   ============================================================ */
let currentLang = 'en';
function t(key, vars){
  let str = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key] || key;
  if(vars){ Object.keys(vars).forEach(k=>{ str = str.split('{'+k+'}').join(vars[k]); }); }
  return str;
}
function currentLocale(){ return currentLang==='es' ? 'es-ES' : currentLang==='pt' ? 'pt-PT' : 'en-US'; }
const SEA_STATE_KEYS = {'Calm':'sea.calm','Slight':'sea.slight','Moderate':'sea.moderate','Rough':'sea.rough','Very Rough':'sea.veryRough'};
function seaStateLabel(v){ return v ? (SEA_STATE_KEYS[v] ? t(SEA_STATE_KEYS[v]) : v) : ''; }
function compassLabel(v){ return v ? t('compass.'+v) : ''; }
const SKY_KEYS = {'Clear / Sunny':'sky.clear','Partly Cloudy':'sky.partlyCloudy','Cloudy':'sky.cloudy','Fog':'sky.fog','Rain':'sky.rain','Thunderstorm':'sky.thunderstorm','Snow':'sky.snow'};
const SKY_ICONS = {'Clear / Sunny':'☀️','Partly Cloudy':'⛅','Cloudy':'☁️','Fog':'🌫️','Rain':'🌧️','Thunderstorm':'⛈️','Snow':'❄️'};
function skyLabel(v){ return v ? (SKY_KEYS[v] ? t(SKY_KEYS[v]) : v) : ''; }
function skyIcon(v){ return v ? (SKY_ICONS[v] || '') : ''; }
// Walks every element tagged with data-i18n / data-i18n-ph / data-i18n-title
// and sets its text/placeholder/title from the current language. Static
// markup only — dynamic screens (history list, trip detail, etc.) re-render
// themselves from JS and already call t() directly, so re-rendering the
// current screen after this covers those.
function applyStaticTranslations(){
  document.querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{ el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{ el.title = t(el.getAttribute('data-i18n-title')); });
  document.documentElement.lang = currentLang;
  document.documentElement.dir = (currentLang==='he') ? 'rtl' : 'ltr';
  document.querySelectorAll('#languageChips .chip').forEach(el=>{ el.classList.toggle('active', el.getAttribute('data-lang')===currentLang); });
  renderThemeSettingUI(document.documentElement.getAttribute('data-theme')||'light');
}
// Re-renders whichever dynamic screens/elements are currently live so a
// language switch takes effect immediately without navigating away and back.
function refreshDynamicScreensForLanguage(){
  const activeScreen = document.querySelector('.screen.active');
  const activeName = activeScreen ? activeScreen.id.replace('screen-','') : null;
  greet(); renderHomeStats();
  if(activeName==='history') renderHistory();
  if(activeName==='boats') renderBoats();
  if(activeName==='crew') renderCrew();
  if(activeName==='resume') renderResume();
  if(activeName==='detail' && openTripId) openTripDetail(openTripId);
  if(currentTrip){
    renderSkipperChip(); renderAddedCrewChips();
    const label = document.getElementById('endJourneyBtnLabel');
    if(label) label.textContent = currentTrip.isEditing ? t('active.saveChanges') : currentTrip.isManual ? t('active.saveLogEntry') : t('active.endJourney');
    refreshLogUnitsUI();
  }
  updateRecordingBanner(activeName);
}
async function setLanguage(lang){
  if(!TRANSLATIONS[lang]) return;
  currentLang = lang;
  state.profile.language = lang;
  await storeSet(KEYS.PROFILE, state.profile);
  applyStaticTranslations();
  refreshDynamicScreensForLanguage();
}

